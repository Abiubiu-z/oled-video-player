/**
 * ============================================================================
 *  OLED视频播放器 - STM32端（主程序）
 * ============================================================================
 *  芯片：STM32F103C8T6 (Cortex-M3, 72MHz, 64KB Flash, 20KB SRAM)
 *
 *  功能概述：
 *    1. 上电后初始化OLED显示屏（软件模拟I2C，PB8=SCL, PB9=SDA）
 *    2. 初始化USART1串口（921600bps），使能接收中断
 *    3. 显示启动画面"START"，等待PC端通过串口发送视频帧
 *    4. 主循环持续调用OLED_Update()，将显存数据通过I2C刷新到屏幕
 *    5. USART1接收中断服务函数负责将接收到的数据写入OLED显存
 *
 *  硬件连接：
 *    ┌─────────────────────────────────────────────────┐
 *    │  OLED (0.96寸 SSD1306)  ←→  STM32F103C8T6      │
 *    │  SCL (I2C时钟)           →  PB8                 │
 *    │  SDA (I2C数据)           →  PB9                 │
 *    │  VCC (3.3V)              →  3.3V                │
 *    │  GND                     →  GND                 │
 *    ├─────────────────────────────────────────────────┤
 *    │  CH340 (USB转串口)       ←→  STM32F103C8T6      │
 *    │  TXD                      →  PA10 (USART1 RX)   │
 *    │  RXD                      ←  PA9  (USART1 TX)   │
 *    │  GND                     ——  GND                │
 *    └─────────────────────────────────────────────────┘
 *
 *  通信协议：
 *    - 波特率：921600 bps
 *    - 数据位：8位，无校验，1停止位（8N1）
 *    - 帧格式：1字节同步头(0xAA) + 1024字节图像数据(8页×128列)
 *    - STM32收到0xAA时复位显存写入指针(p0=0, p1=0)，确保帧对齐
 *    - 后续1024字节按顺序填入OLED_DisplayBuf[0..7][0..127]
 *
 *  数据存储格式（OLED显存）：
 *    屏幕64×128像素 → 8页×128列
 *    每页8像素高，每列1字节表示8个纵向像素（Bit0在上，Bit7在下）
 *
 *  作者：Abiubiu-z
 *  OLED驱动基于：江协科技 (jiangxiekeji.com)
 * ============================================================================
 */

#include "stm32f10x.h"      // STM32F10x标准外设库
#include "Delay.h"          // 微秒/毫秒延时
#include "Serial.h"         // 串口驱动（含帧同步接收中断）
#include "OLED.h"           // OLED驱动（SSD1306, 软件I2C）

/**
 * @brief  程序入口
 *
 *  执行流程：
 *  1. 初始化OLED（配置I2C引脚 + 发送SSD1306初始化命令）
 *  2. 初始化USART1（配置波特率921600 + 使能接收中断）
 *  3. 显示"START"启动画面
 *  4. 进入无限循环，持续刷新OLED屏幕
 *
 *  注意：主循环只负责刷新显示，显存数据由USART1_IRQHandler中断服务函数写入
 *       这种设计避免了主循环中的串口轮询，保证了显示的流畅性
 */
int main(void)
{
    /*---------- 第1步：OLED初始化 ----------*/
    // 包括：GPIO配置(开漏输出，模拟I2C)、SSD1306初始化命令序列
    // 详见OLED.c中的OLED_Init()函数
    OLED_Init();

    /*---------- 第2步：串口初始化 ----------*/
    // USART1: 921600bps, 8N1, 使能接收中断(RXNE)
    // 中断优先级: 抢占1, 子优先级1
    // 详见Serial.c中的Serial_Init()函数
    Serial_Init();

    /*---------- 第3步：显示启动画面 ----------*/
    OLED_Clear();                                       // 清空显存（全屏黑）
    OLED_ShowString(40, 24, "START", OLED_8X16);       // 坐标(40,24)显示"START"
    OLED_Update();                                      // 将显存通过I2C发送到OLED

    /*---------- 第4步：主循环 ----------*/
    // 持续将显存刷新到OLED屏幕
    // 显存由USART1中断服务函数实时更新（非阻塞方式）
    // 每调用一次OLED_Update()，完整的1024字节显存通过I2C发送到SSD1306
    while (1)
    {
        OLED_Update();  // 8页 × 128列 = 1024字节，通过软件I2C逐字节发送
    }
}
